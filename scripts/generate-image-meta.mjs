// تولید lib/imageSizes.ts از روی فایل‌های public/images
// اجرا: npm i -D sharp && node scripts/generate-image-meta.mjs
import sharp from "sharp";
import fs from "node:fs";
import path from "node:path";

const root = path.resolve("public");
const walk = (d) =>
  fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]));

const out = {};
for (const f of walk(path.join(root, "images")).sort()) {
  if (!/\.(png|jpe?g|webp)$/i.test(f)) continue;
  const m = await sharp(f).metadata();
  out["/" + path.relative(root, f).split(path.sep).join("/")] = [m.width, m.height];
}
const body = `// AUTO-GENERATED by scripts/generate-image-meta.mjs — ابعاد واقعی تصاویر برای جلوگیری از CLS
export const IMAGE_SIZES: Record<string, readonly [number, number]> = {
${Object.entries(out).map(([k, v]) => `  "${k}": [${v[0]}, ${v[1]}],`).join("\n")}
};
`;
fs.writeFileSync(path.resolve("lib/imageSizes.ts"), body);
console.log(Object.keys(out).length, "images");
